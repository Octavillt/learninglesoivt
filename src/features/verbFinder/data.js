// Banco de verbos del módulo «Verbos a la mano»: los irregulares del material
// del curso, los regulares que ya usaba la plataforma y los frasales de las
// lecciones. Cada entrada es plana para poder serializarla y compararla sin
// conversiones; las formas alternativas van como elementos del arreglo.

const forms = value => value.split(" / ");

// esPast es el pretérito en 3.ª persona (él / ella), con los mismos
// significados y el mismo orden que es.
const irr = (base, past, participle, es, esPast, note) => ({
  base,
  past: forms(past),
  participle: forms(participle),
  es,
  esPast,
  kind: "irregular",
  ...(note ? { note } : {}),
});

const reg = (base, past, ed, es, esPast, note) => ({
  base,
  past: forms(past),
  participle: forms(past),
  es,
  esPast,
  kind: "regular",
  ed,
  ...(note ? { note } : {}),
});

// Frasales: heredan el kind (y el sonido de -ed) de su verbo base.
const phrIrr = (base, past, participle, es, esPast) => ({ ...irr(base, past, participle, es, esPast), phrasal: true });
const phrReg = (base, past, ed, es, esPast) => ({ ...reg(base, past, ed, es, esPast), phrasal: true });

